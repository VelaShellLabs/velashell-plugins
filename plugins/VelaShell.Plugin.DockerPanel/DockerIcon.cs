/// 图标成套 —— 它要的是融进界面;标签页这一个要的是在一条挤满标签的标签条上被一眼认出来,
/// 那是品牌标才做得到的事。
/// </para>
/// <para>
/// 单独一个文件而不是塞进 <see cref="DockerPanelPlugin" />:一千多字符的路径数据横在开面板的
/// 逻辑中间,读代码的人要翻很久才能翻过去(Redis 插件的 <c>RedisIcon</c>、AI 插件的
